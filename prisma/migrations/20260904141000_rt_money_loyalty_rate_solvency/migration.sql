-- 19-د (عدسة المال) — حدّ الملاءة على معدّلات الولاء.
--
-- `stores_loyalty_rates_ck` يحدّ كل معدّل وحده: earn_per_1000 حتى 1000،
-- point_value_iqd حتى 10000. لكن حاصل ضربهما لم يكن محدوداً إطلاقاً — تاجر
-- يضبط 1000 و10000 على متجره بصلاحية settings.manage وبلا مراجعة، فتصير كل
-- 1000 دينار بضاعة نقاطاً تُصرف بعشرة ملايين دينار.
--
-- القاعدة الجديدة: البيعة لا تمنح نقاطاً تساوي أكثر من البيعة نفسها. ليست رأياً
-- تسويقياً في كرم البرنامج، بل الخط الذي يبدأ بعده البرنامج بطبع قدرة صرف من
-- العدم. المعدّل الافتراضي (10 × 10 = 100) برنامج 10% ويقع داخل الحدّ بعشرة
-- أضعاف، فلا يُرفض أي تصميم برنامج يمكن الوصول إليه اليوم.
--
-- NOT VALID مقصودة: القيد يسري على كل إدراج وعلى كل تعديل لصف قائم، ولا يفحص
-- الصفوف الموجودة — فهجرة تشدّ CHECK يجب ألا تفشل على بيانات مكتوبة سلفاً.
-- التاجر الذي ضبط معدّلاً خارج الحدّ قبل اليوم يبقى كما هو حتى يمسّ إعداداته،
-- وعندها يُطالَب بمعدّل سليم. المعالجة الرجعية قرار مالك، لا أثر جانبي لهجرة.

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'stores_loyalty_solvency_ck') THEN
    ALTER TABLE stores ADD CONSTRAINT stores_loyalty_solvency_ck
      CHECK (loyalty_earn_per_1000 * loyalty_point_value_iqd <= 1000) NOT VALID;
  END IF;
END $$;
